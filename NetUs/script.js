/* ---------------------------------------------------------------------
   Screen 1 — Video intro
   ----------------------------------------------------------------------
   Plays assets/background.mp4 once, full-screen (muted, with an unmute
   button — browsers block auto-playing sound without a click). When it
   ends, the SAME <video> element is handed over to the profile screen
   and restarted as a quiet looping ambient background — no need to load
   the file twice.
   --------------------------------------------------------------------- */

function initVideoIntro() {
  const video = document.getElementById("bg-video");
  const playBtn = document.getElementById("intro-play-btn");
  let advanced = false;

  const goToProfiles = () => {
    if (advanced) return;
    advanced = true;
    video.remove();
    document.getElementById("bg-fallback").classList.add("show");
    showScreen("screen-profiles");
  };

  video.addEventListener("ended", goToProfiles);
  video.addEventListener("error", goToProfiles);

  playBtn.addEventListener("click", () => {
    playBtn.remove();
    // Small delay before starting playback, so it has a moment to buffer
    // when loading from a live server.
    const startDelay = 2000 + Math.random() * 2000; // 2-4s
    setTimeout(() => {
      if (advanced) return;
      video.play().catch(() => goToProfiles());
    }, startDelay);
  });
}

