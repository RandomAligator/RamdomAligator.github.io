function paletteFor(index) {
  return FALLBACK_PALETTES[index % FALLBACK_PALETTES.length];
}

function el(tag, className, html) {
  const node = document.createElement(tag);
  if (className) node.className = className;
  if (html !== undefined) node.innerHTML = html;
  return node;
}

function categoryById(id) {
  return CATEGORIES.find((c) => c.id === id);
}

/* ---------------------------------------------------------------------
   How many cards sit in one scrollable row before the rest wrap onto a
   new row. Lower this if you want shorter, more numerous rows.
   --------------------------------------------------------------------- */
const ITEMS_PER_ROW = 8;

function chunk(arr, size) {
  const out = [];
  for (let i = 0; i < arr.length; i += size) out.push(arr.slice(i, i + size));
  return out;
}

// Builds one <div class="row"> containing its own title, arrows, and
// horizontally-scrolling track. `startIndex` is this row's offset into
// `fullMediaArray`, so lightbox prev/next still cycles the whole category.
function buildMediaRow(title, items, startIndex, fullMediaArray, rowId) {
  const row = el("div", "row");
  row.id = rowId;

  if (title) row.appendChild(el("h3", "row-title", title));

  const wrap = el("div", "row-track-wrap");

  const track = el("div", "row-track");
  track.id = `${rowId}-track`;

  const leftBtn = el("button", "row-arrow row-arrow--left", "&#10094;");
  leftBtn.type = "button";
  leftBtn.dataset.target = track.id;
  leftBtn.dataset.dir = "-1";
  leftBtn.setAttribute("aria-label", "Scroll left");

  const rightBtn = el("button", "row-arrow row-arrow--right", "&#10095;");
  rightBtn.type = "button";
  rightBtn.dataset.target = track.id;
  rightBtn.dataset.dir = "1";
  rightBtn.setAttribute("aria-label", "Scroll right");

  items.forEach((item, i) => {
    track.appendChild(buildMediaCard(item, startIndex + i, fullMediaArray));
  });

  wrap.appendChild(leftBtn);
  wrap.appendChild(track);
  wrap.appendChild(rightBtn);
  row.appendChild(wrap);
  return row;
}

/* ---------------------------------------------------------------------
   Ambient floating hearts (canvas) — the one "signature" flourish
   --------------------------------------------------------------------- */

function initHearts() {
  const canvas = document.getElementById("hearts-canvas");
  const ctx = canvas.getContext("2d");
  let particles = [];
  let raf = null;

  function resize() {
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
  }

  function spawn() {
    particles.push({
      x: Math.random() * canvas.width,
      y: canvas.height + 20,
      size: 10 + Math.random() * 14,
      speed: 0.4 + Math.random() * 0.6,
      drift: (Math.random() - 0.5) * 0.6,
      opacity: 0.12 + Math.random() * 0.22,
      wobble: Math.random() * Math.PI * 2,
    });
  }

  function drawHeart(x, y, size, opacity) {
    ctx.save();
    ctx.globalAlpha = opacity;
    ctx.fillStyle = "#ff4d6d";
    ctx.translate(x, y);
    ctx.beginPath();
    const s = size / 16;
    ctx.moveTo(0, 4 * s);
    ctx.bezierCurveTo(-8 * s, -6 * s, -16 * s, 2 * s, 0, 14 * s);
    ctx.bezierCurveTo(16 * s, 2 * s, 8 * s, -6 * s, 0, 4 * s);
    ctx.fill();
    ctx.restore();
  }

  function tick() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    particles.forEach((p) => {
      p.y -= p.speed;
      p.wobble += 0.02;
      p.x += Math.sin(p.wobble) * p.drift;
      drawHeart(p.x, p.y, p.size, p.opacity);
    });
    particles = particles.filter((p) => p.y > -30);
    if (Math.random() < 0.035) spawn();
    raf = requestAnimationFrame(tick);
  }

  resize();
  window.addEventListener("resize", resize);
  raf = requestAnimationFrame(tick);
}

