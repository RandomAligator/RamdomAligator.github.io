function thumbSrcFor(item) {
  if (item.type === "photo") return resolvePhotoSrc(item.src);
  if (item.poster) return resolvePhotoSrc(item.poster);
  if (isDriveUrl(item.src)) return driveThumbUrl(item.src);
  return item.src; // local video, no poster: browser shows first frame
}

function buildMediaCard(item, index, mediaArray) {
  const card = el("div", "card");
  card.tabIndex = 0;

  if (item.type === "video") {
    if (isDriveUrl(item.src) && !item.poster) {
      // Drive video with no local poster: show its thumbnail as an <img>
      // (a <video> tag can't reliably load a hotlinked Drive stream).
      const img = document.createElement("img");
      img.src = driveThumbUrl(item.src);
      img.loading = "lazy";
      img.alt = "";
      card.appendChild(img);
    } else {
      const video = document.createElement("video");
      video.src = isDriveUrl(item.src) ? "" : item.src;
      video.poster = item.poster ? resolvePhotoSrc(item.poster) : "";
      video.muted = true;
      video.preload = "metadata";
      card.appendChild(video);
    }
    card.appendChild(el("span", "card-play", "&#9658;"));
  } else {
    const img = document.createElement("img");
    img.src = resolvePhotoSrc(item.src);
    img.loading = "lazy";
    img.alt = "";
    card.appendChild(img);
  }

  const open = () => openLightbox(mediaArray, index);
  card.addEventListener("click", open);
  card.addEventListener("keydown", (e) => {
    if (e.key === "Enter" || e.key === " ") {
      e.preventDefault();
      open();
    }
  });

  return card;
}

function buildCategoryPreviewCard(cat, i) {
  const card = el("div", "card category-card");
  const [a, b] = paletteFor(i);

  const firstPhoto = cat.media.find((m) => m.type === "photo");
  const firstThumb = cat.media[0] ? thumbSrcFor(cat.media[0]) : null;

  if (firstThumb) {
    const img = document.createElement("img");
    img.src = firstThumb;
    img.alt = cat.label;
    img.onerror = () => {
      img.style.background = `linear-gradient(145deg, ${a}, ${b})`;
      img.removeAttribute("src");
    };
    card.appendChild(img);
  } else {
    card.style.background = `linear-gradient(145deg, ${a}, ${b})`;
  }

  card.appendChild(
    el("span", "card-label", `${cat.emoji || "💗"} ${cat.label}`),
  );
  card.addEventListener("click", () => openCategory(cat.id));
  return card;
}

