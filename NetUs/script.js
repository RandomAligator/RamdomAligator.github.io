/* ---------------------------------------------------------------------
   Lightbox — player + pinch/scroll zoom + drag pan
   --------------------------------------------------------------------- */

function openLightbox(mediaArray, index) {
  lightboxMedia = mediaArray;
  lightboxIndex = index;
  renderLightbox();
  document.getElementById("lightbox").classList.add("open");
  document.body.style.overflow = "hidden";
}

function closeLightbox() {
  document.getElementById("lightbox").classList.remove("open");
  document.getElementById("lightbox-stage").innerHTML = "";
  document.body.style.overflow = "";
}

function stepLightbox(dir) {
  lightboxIndex =
    (lightboxIndex + dir + lightboxMedia.length) % lightboxMedia.length;
  renderLightbox();
}

function renderLightbox() {
  const stage = document.getElementById("lightbox-stage");
  stage.innerHTML = "";
  const item = lightboxMedia[lightboxIndex];

  document.getElementById("lightbox-counter").textContent =
    `${lightboxIndex + 1} / ${lightboxMedia.length}`;

  if (item.type === "video") {
    if (isDriveUrl(item.src)) {
      // Drive can't be reliably hotlinked into a <video> tag — embed
      // Drive's own player instead. Custom zoom/pan doesn't apply to video.
      const iframe = document.createElement("iframe");
      iframe.src = driveVideoEmbedUrl(item.src);
      iframe.allow = "autoplay";
      iframe.style.cssText =
        "width:92vw;height:82vh;max-width:960px;border:0;border-radius:4px;background:#000;";
      stage.appendChild(iframe);
    } else {
      const video = document.createElement("video");
      video.src = item.src;
      video.controls = true;
      video.autoplay = true;
      video.playsInline = true;
      stage.appendChild(video);
    }
  } else {
    const img = document.createElement("img");
    img.src = resolvePhotoSrc(item.src);
    img.alt = "";
    stage.appendChild(img);
    initZoomPan(img);
  }
}

function initZoomPan(img) {
  let scale = 1,
    originX = 0,
    originY = 0;
  let dragging = false,
    lastX = 0,
    lastY = 0;

  const apply = () => {
    img.style.transform = `translate(${originX}px, ${originY}px) scale(${scale})`;
  };

  img.addEventListener(
    "wheel",
    (e) => {
      e.preventDefault();
      const delta = e.deltaY > 0 ? -0.15 : 0.15;
      scale = Math.min(4, Math.max(1, scale + delta));
      if (scale === 1) {
        originX = 0;
        originY = 0;
      }
      apply();
    },
    { passive: false },
  );

  img.addEventListener("dblclick", () => {
    scale = scale > 1 ? 1 : 2.5;
    originX = 0;
    originY = 0;
    apply();
  });

  img.addEventListener("pointerdown", (e) => {
    if (scale === 1) return;
    dragging = true;
    img.classList.add("dragging");
    lastX = e.clientX;
    lastY = e.clientY;
    img.setPointerCapture(e.pointerId);
  });

  img.addEventListener("pointermove", (e) => {
    if (!dragging) return;
    originX += e.clientX - lastX;
    originY += e.clientY - lastY;
    lastX = e.clientX;
    lastY = e.clientY;
    apply();
  });

  const endDrag = () => {
    dragging = false;
    img.classList.remove("dragging");
  };
  img.addEventListener("pointerup", endDrag);
  img.addEventListener("pointerleave", endDrag);

  // basic pinch-to-zoom for touch
  let pinchStartDist = null,
    pinchStartScale = 1;
  img.addEventListener("touchstart", (e) => {
    if (e.touches.length === 2) {
      pinchStartDist = Math.hypot(
        e.touches[0].clientX - e.touches[1].clientX,
        e.touches[0].clientY - e.touches[1].clientY,
      );
      pinchStartScale = scale;
    }
  });
  img.addEventListener(
    "touchmove",
    (e) => {
      if (e.touches.length === 2 && pinchStartDist) {
        e.preventDefault();
        const dist = Math.hypot(
          e.touches[0].clientX - e.touches[1].clientX,
          e.touches[0].clientY - e.touches[1].clientY,
        );
        scale = Math.min(
          4,
          Math.max(1, pinchStartScale * (dist / pinchStartDist)),
        );
        apply();
      }
    },
    { passive: false },
  );
}

function initLightboxControls() {
  document
    .getElementById("lightbox-close")
    .addEventListener("click", closeLightbox);
  document
    .getElementById("lightbox-prev")
    .addEventListener("click", () => stepLightbox(-1));
  document
    .getElementById("lightbox-next")
    .addEventListener("click", () => stepLightbox(1));

  document.getElementById("lightbox").addEventListener("click", (e) => {
    if (e.target.id === "lightbox") closeLightbox();
  });

  document.addEventListener("keydown", (e) => {
    const open = document.getElementById("lightbox").classList.contains("open");
    if (!open) return;
    if (e.key === "Escape") closeLightbox();
    if (e.key === "ArrowLeft") stepLightbox(-1);
    if (e.key === "ArrowRight") stepLightbox(1);
  });
}

