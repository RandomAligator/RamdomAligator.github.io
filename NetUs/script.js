/* ---------------------------------------------------------------------
   Google Drive support
   ----------------------------------------------------------------------
   Photos: paste any Drive share link (e.g. from "Copy link" with sharing
   set to "Anyone with the link") straight into "src" — it's auto-converted
   to a direct-viewable image URL. Example:
     { type: "photo", src: "https://drive.google.com/file/d/FILE_ID/view" }

   Videos: Drive does NOT reliably serve hotlinked video to a <video> tag
   (it throttles/blocks this at scale). If a video's "src" is a Drive link,
   this site falls back to embedding Drive's own player in an iframe, which
   works but loses the custom zoom/pan controls. For anything beyond a
   handful of clips, hosting the .mp4 file directly in your GitHub repo
   (or another video host) is far more reliable — see README.md.
   --------------------------------------------------------------------- */

function isDriveUrl(src) {
  return typeof src === "string" && src.includes("drive.google.com");
}

function extractDriveId(url) {
  const m =
    url.match(/\/d\/([a-zA-Z0-9_-]+)/) || url.match(/[?&]id=([a-zA-Z0-9_-]+)/);
  return m ? m[1] : null;
}

// Direct-viewable image URL for a Drive-hosted photo.
function driveImageUrl(idOrUrl) {
  const id = isDriveUrl(idOrUrl) ? extractDriveId(idOrUrl) : idOrUrl;
  return id ? `https://lh3.googleusercontent.com/d/${id}` : idOrUrl;
}

// Drive's own thumbnail endpoint — used for video poster/thumb fallback.
function driveThumbUrl(idOrUrl, width = 500) {
  const id = isDriveUrl(idOrUrl) ? extractDriveId(idOrUrl) : idOrUrl;
  return id
    ? `https://drive.google.com/thumbnail?id=${id}&sz=w${width}`
    : idOrUrl;
}

// Embeddable preview URL for a Drive-hosted video (used as an iframe).
function driveVideoEmbedUrl(idOrUrl) {
  const id = isDriveUrl(idOrUrl) ? extractDriveId(idOrUrl) : idOrUrl;
  return id ? `https://drive.google.com/file/d/${id}/preview` : idOrUrl;
}

// Resolve any photo src (local path or Drive link) to something an <img> can load.
function resolvePhotoSrc(src) {
  return isDriveUrl(src) ? driveImageUrl(src) : src;
}

